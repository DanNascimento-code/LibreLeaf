TRANSLATIONS = {"pt-BR": PT, "es-419": ES}


def normalize_language(value: str | None) -> str:
    if not value:
        return "en"
    candidate = value.strip()
    aliases = {"pt": "pt-BR", "pt-br": "pt-BR", "es": "es-419", "es-419": "es-419"}
    normalized = aliases.get(candidate.casefold(), candidate)
    return normalized if normalized in SUPPORTED_LANGUAGES else "en"


def translator(language: str) -> Callable[[str], str]:
    messages = TRANSLATIONS.get(language, {})
    return lambda message: messages.get(message, message)
